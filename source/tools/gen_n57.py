"""Generate the experimental N57 table from nbtevo-diag's factory-derived catalog."""
import argparse
from pathlib import Path
import runpy

p = argparse.ArgumentParser(description=__doc__)
p.add_argument("--catalog", required=True, type=Path, help="nbtevo-diag/nbtevo_diag/signals.py")
p.add_argument("--check", action="store_true")
a = p.parse_args()
signals = runpy.run_path(str(a.catalog))["N57_DYNAMIC"]
lines = ["/* Generated by tools/gen_n57.py from nbtevo-diag N57_DYNAMIC (Apache-2.0).",
         " * Factory ISTA d73n57*.prg scales; experimental until checked on the target car. */"]
for s in signals:
    d = s.decode
    assert s.service == "dyn" and s.ecu == 0x12 and d.width in (2, 4) and not d.signed
    assert s.lo is not None and s.hi is not None
    lines.append('N57_SIGNAL("%s", 0x%04X, %d, %d, %d, %r, %r, %r)' %
                 (s.key, s.addr, d.width, d.num, d.den, float(d.offset), float(s.lo), float(s.hi)))
text = "\n".join(lines) + "\n"
out = Path(__file__).resolve().parents[1] / "native/src/common/n57_signals.def"
if a.check:
    assert out.read_text() == text, "N57 table differs from the source catalog; regenerate it"
else:
    out.write_text(text)
print("N57 catalog: %d signals%s" % (len(signals), " checked" if a.check else " generated"))
